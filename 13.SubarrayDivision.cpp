int birthday(vector<int> s, int d, int m) {
    if(s.size()==0) 
    {return 0;}
    
    int ans=0,length=0,sum=0,l=0;
    
    for(int r=0;r<s.size();r++){
        //Agar Specified Length Mil Jae
        sum+=s[r];
        length++;
         
        if(length>m){
            sum-=s[l];
            l++;
            length--;
        }
        
        if(length==m && sum==d)
        {
            ans++;        
        }
    }
    return ans;
}

